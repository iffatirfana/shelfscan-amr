class WorldTests(unittest.TestCase):
    def test_world_needs_no_remote_proto(self):
        text = wbt(make(1), "R2025a")
        self.assertNotIn("EXTERNPROTO", text)
        self.assertNotIn("webots://", text)
        self.assertTrue(text.startswith("#VRML_SIM R2025a utf8"))

    def test_robot_devices_match_driver(self):
        text = wbt(make(1), "R2025a", "data_capture")
        for dev in ('"left wheel motor"', '"right wheel motor"', '"gps"', '"imu"',
                    '"camera"', "DEF CAM Camera", 'controller "data_capture"'):
            self.assertIn(dev, text)

    def test_camera_at_item_height(self):
        lay = make(1)
        z = next(iter(lay["slots"].values()))["z"]
        self.assertLess(abs(CAM_Z - z), ITEM[2] / 2)

    def test_layout_deterministic_per_seed(self):
        self.assertEqual(make(7), make(7))
        self.assertNotEqual(make(7)["slots"], make(8)["slots"])

    def test_start_pose_in_free_aisle(self):
        lay = make(1)
        self.assertEqual(lay["start_pose"][0], Driver.AISLE_X)
        xs = [s["x"] for s in lay["slots"].values()]
        self.assertLess(Driver.AISLE_X, min(xs) - 0.45)


class InsetDisplayTests(unittest.TestCase):
    """The recording Display (make_world.py --display, HUD_DISPLAY=1).

    The point of the flag is that a measured run cannot be affected by it, so
    what is pinned here is the ABSENCE of any difference when it is off."""

    def test_off_by_default_no_display_anywhere_in_the_world(self):
        for seed in (0, 5, 13, 101):
            for label in (None, "qr", "barcode"):
                text = wbt(make(seed, label=label), "R2025a")
                self.assertNotIn("Display", text,
                                 f"seed {seed} label {label}")

    def test_the_robot_node_is_byte_identical_with_the_flag_off(self):
        """Not 'equivalent' - the same string. An eval world is generated by
        this function and compared against committed results."""
        self.assertEqual(robot_node(0.0, 1.0, 0.0, "shelfscan_audit"),
                         robot_node(0.0, 1.0, 0.0, "shelfscan_audit",
                                    display=False))

    def test_the_whole_world_is_byte_identical_with_the_flag_off(self):
        lay = make(13, label="qr")
        self.assertEqual(wbt(lay, "R2025a"),
                         wbt(lay, "R2025a", "shelfscan_audit", display=False))

    def test_the_flag_adds_exactly_one_display_named_inset(self):
        text = wbt(make(13, label="qr"), "R2025a", "shelfscan_audit",
                   display=True)
        self.assertEqual(text.count("Display"), 1)
        self.assertIn('DEF INSET Display { name "inset" '
                      f'width {CAM_W} height {CAM_H} }}', text)

    def test_the_display_matches_the_camera_size(self):
        """The controller pastes the camera frame on unresampled, so a
        mismatch would silently crop the inset."""
        text = wbt(make(13, label="qr"), "R2025a", "shelfscan_audit",
                   display=True)
        self.assertIn(f'name "camera" translation 0.05 0 0 '
                      f'width {CAM_W} height {CAM_H}', text)

    def test_the_flag_adds_nothing_but_that_node(self):
        lay = make(13, label="qr")
        off = wbt(lay, "R2025a", "shelfscan_audit", display=False)
        on = wbt(lay, "R2025a", "shelfscan_audit", display=True)
        node = (f' DEF INSET Display {{ name "inset" '
                f'width {CAM_W} height {CAM_H} }}')
        self.assertEqual(on.replace(node, "", 1), off)

    def test_the_display_carries_no_physics_and_no_bounding_object(self):
        """It is a sink. If it had mass or a collision body it could perturb
        the carriage the camera rides on."""
        text = wbt(make(13, label="qr"), "R2025a", "shelfscan_audit",
                   display=True)
        i = text.index("DEF INSET Display {")
        node = text[i:text.index("}", i) + 1]
        for banned in ("physics", "boundingObject", "mass", "children"):
            self.assertNotIn(banned, node)


class OverlayPerspectiveTests(unittest.TestCase):
    """Where Webots draws the two device overlays.

    Both default to 0;0, so without this the camera overlay sits exactly on
    the inset and the annotated frame is painted every step and never seen -
    which is what the first recording actually showed."""

    @staticmethod
    def _parse():
        out = {}
        for o in OVERLAYS:
            dev, rest = o.split(";", 1)
            f = rest.split(";")
            out[dev.split(":")[1]] = (f[0] == "1", (f[2], f[3]))
        return out

    def test_no_two_visible_overlays_share_a_position(self):
        """Webots defaults every overlay to 0;0 and draws them stacked, so two
        visible ones at the same spot means the lower is painted and never
        seen - which is what the first recording did."""
        seen = [p for vis, p in self._parse().values() if vis]
        self.assertEqual(len(seen), len(set(seen)), OVERLAYS)

    def test_the_annotated_inset_is_the_visible_one(self):
        """A Camera overlay is rendered by Webots from the sensor and cannot
        be drawn on, so showing it beside the inset puts an un-boxed copy of
        the same QR next to a boxed one. The inset carries the same frame plus
        the boxes, so it is the one that is shown."""
        p = self._parse()
        self.assertTrue(p["inset"][0], "the inset must be visible")
        self.assertFalse(p["camera"][0],
                         "the raw camera overlay cannot carry the boxes")

    def test_the_inset_clears_the_hud_text_panel(self):
        """shelfscan.hud puts its panel at y = 0.655 and the overlay is 480 of
        a 747-pixel view, so an overlay at y = 0 ends at 0.643."""
        from shelfscan.hud import PANEL_Y, VIEW_ASPECT      # noqa: F401
        for o in OVERLAYS:
            y = float(o.split(";")[4])
            self.assertLess(y + CAM_H / 747.0, PANEL_Y, o)

    def test_writes_the_lines_into_a_fresh_wbproj(self):
        with tempfile.TemporaryDirectory() as d:
            world = Path(d) / "w.wbt"
            world.write_text("#VRML_SIM R2025a utf8")
            proj = write_overlay_perspective(world)
            self.assertEqual(proj.name, ".w.wbproj")
            text = proj.read_text()
            self.assertTrue(text.startswith("Webots Project File version"))
            for o in OVERLAYS:
                self.assertIn(PERSP_KEY + o, text)

    def test_keeps_every_other_setting_in_an_existing_wbproj(self):
        """Webots stores the viewpoint and console layout in the same file;
        replacing the whole thing would throw away a tuned recording set-up."""
        with tempfile.TemporaryDirectory() as d:
            world = Path(d) / "w.wbt"
            world.write_text("#VRML_SIM R2025a utf8")
            proj = Path(d) / ".w.wbproj"
            proj.write_text("\n".join([
                "Webots Project File version R2025a",
                "maximizedDockId: -1",
                "orthographicViewHeight: 1",
                PERSP_KEY + "shelfscan:camera;1;1;0;0"]) + "\n")
            write_overlay_perspective(world)
            text = proj.read_text()
            self.assertIn("maximizedDockId: -1", text)
            self.assertIn("orthographicViewHeight: 1", text)
            self.assertEqual(text.count(PERSP_KEY), len(OVERLAYS))
            for o in OVERLAYS:
                self.assertIn(PERSP_KEY + o, text)


class DemoVisualsGateTests(unittest.TestCase):
    """The recording visuals are gated because they are an INPUT change.

    v4 was trained on frames captured against blue-and-orange racking with an
    open-backed bay-mouth pallet. Repainting the racking and closing the
    pallet back changes what the camera sees, and on seeds 101-104 it moved
    103 S1-0-1 from UNVERIFIED to EMPTY at conf 0.71 on a bay that really
    holds sku_B - "I don't know" became a confident wrong answer. So the demo
    world gets them and every measured run gets the world v4 was trained on.
    """

    def test_the_default_world_is_the_one_v4_was_trained_on(self):
        """No argument, no env, no keyword: the trained-on colours."""
        text = wbt(make(1), "R2025a")
        self.assertIn("baseColor 0.0900 0.2400 0.6000", text)   # blue upright
        self.assertIn("baseColor 0.9300 0.4200 0.0800", text)   # orange beam
        for name, (r, g, b, *_) in DEMO_PALETTE.items():
            self.assertNotIn(f"baseColor {r:.4f} {g:.4f} {b:.4f}", text,
                             f"{name} demo paint leaked into the eval world")

    def test_demo_repaints_only_the_racking(self):
        text = wbt(make(1), "R2025a", demo=True)
        for name, (r, g, b, *_) in DEMO_PALETTE.items():
            self.assertIn(f"baseColor {r:.4f} {g:.4f} {b:.4f}", text, name)
        self.assertNotIn("baseColor 0.0900 0.2400 0.6000", text)
        self.assertNotIn("baseColor 0.9300 0.4200 0.0800", text)

    def test_demo_overrides_name_real_palette_entries(self):
        """A typo'd override would silently never apply."""
        for name in DEMO_PALETTE:
            self.assertIn(name, PALETTE, name)

    def test_the_def_names_are_the_same_in_both_modes(self):
        """Only the painted value may differ, so the two worlds stay
        comparable - and the names stay honest in both (RACK_BLUE would be a
        lie once --demo paints it grey)."""
        for mode in (False, True):
            text = wbt(make(1), "R2025a", demo=mode)
            self.assertIn("DEF RACK_UPRIGHT PBRAppearance", text)
            self.assertIn("DEF RACK_BEAM PBRAppearance", text)
            self.assertNotIn("RACK_BLUE", text)
            self.assertNotIn("RACK_ORANGE", text)

    def test_the_pallet_back_board_is_demo_only(self):
        """The closed back is gated with the paint: a pallet blocker stands in
        25 of the 300 slots of seeds 101-110, so it is an input change in
        every one of them. Seed 101 has 3."""
        board = 'geometry Box { size 0.4500 0.0220 0.5500 }'
        self.assertNotIn(board, wbt(make(101, label="qr"), "R2025a"))
        self.assertIn(board, wbt(make(101, label="qr"), "R2025a", demo=True))

    def test_a_measured_run_cannot_reach_demo_positionally(self):
        """experiments/run_batch.py calls wbt(lay, version, controller). If
        demo ever moved ahead of display in the signature, that third
        argument would start selecting it."""
        import inspect
        names = list(inspect.signature(wbt).parameters)
        self.assertEqual(names[:3], ["layout", "version", "controller"])
        self.assertGreater(names.index("demo"), 3, names)
        self.assertIs(inspect.signature(wbt).parameters["demo"].default, False)

    def test_run_batch_builds_worlds_without_demo(self):
        """The gate is only real if the batch runner does not pass it."""
        src = (ROOT / "experiments/run_batch.py").read_text(encoding="utf-8")
        self.assertIn("wbt(lay, version, controller)", src)
        self.assertNotIn("demo", src)

    def test_the_flag_does_not_leak_between_builds(self):
        """wbt() owns the module flag the way it owns _SEEN, so a demo build
        must not colour the next eval build in the same process."""
        wbt(make(1), "R2025a", demo=True)
        self.assertIn("baseColor 0.0900 0.2400 0.6000", wbt(make(1), "R2025a"))

    def test_display_does_not_imply_demo(self):
        """A HUD_DISPLAY debugging run on an eval seed should still render the
        world the detector was trained on."""
        text = wbt(make(1), "R2025a", "shelfscan_audit", True)
        self.assertIn('Display {', text)
        self.assertIn("baseColor 0.0900 0.2400 0.6000", text)


